// Hàm này sẽ chạy ngay khi trang web load xong
window.onload = function() {
    
    // --- XỬ LÝ TRANG DANH SÁCH (Chỉ chạy khi có khung #cards) ---
    const container = document.getElementById('cards');
    if (container) {
        loadAllproducts();
    }

    // --- XỬ LÝ TRANG XEM CHI TIẾT (Chỉ chạy khi có khung #detail-name) ---
    const detailName = document.getElementById("detail-name");
    if (detailName) {
        // Sửa lỗi chính tả: windown -> window
        const urlParams = new URLSearchParams(window.location.search);
        const productId = urlParams.get("id");

        if (productId) {
            const searchProduct = productList.find(item => item.id === productId);

            if (searchProduct) {
                // Sửa lỗi chính tả: getElementsById -> getElementById
                document.getElementById("detail-img").src = searchProduct.img;
                document.getElementById("detail-img").alt = searchProduct.name;
                document.getElementById("detail-name").innerText = "Tên sản phẩm: " + searchProduct.name;
                document.getElementById("detail-price").innerText = "Giá bán: " + searchProduct.price;
                document.getElementById("detail-descrition").innerText = "Mô tả: " + searchProduct.description;
            } else {
                document.getElementById("detail-name").innerText = "Sản phẩm chưa được cập nhật dữ liệu";
            }
        } else {
            document.getElementById("detail-name").innerText = "Sản phẩm này không tồn tại";
        }
    }
};

function loadAllproducts() {
    const container = document.getElementById('cards');
    if (container) container.innerHTML = ""; // Xóa sạch danh sách cũ

    productList.forEach(item => {
        addCar(item.img, item.name, item.price, item.id);
    });
}

function addCarFromForm() {
    const img = document.getElementById('car-img')?.value.trim();
    const name = document.getElementById('car-name')?.value.trim();
    const price = document.getElementById('car-price')?.value.trim();
    
    // Sửa lỗi: Khai báo biến id trước khi truyền vào hàm addCar
    const id = "NEW-" + Date.now();

    if (!img || !name || !price) {
        alert('Bạn cần nhập đủ 3 thông tin: Ảnh, Tên xe, Giá');
        return;
    }

    addCar(img, name, price, id);

    // Xoá trắng form sau khi thêm
    document.getElementById('car-img').value = '';
    document.getElementById('car-name').value = '';
    document.getElementById('car-price').value = '';
}

function addCar(img, nameCar, price, id) {
    const container = document.getElementById('cards');
    if (!container) return;

    // Tạo các Element
    const myDiv = document.createElement("div");
    myDiv.className = "product-item";
    myDiv.style.border = "1px solid #ccc"; 
    myDiv.style.margin = "10px";
    myDiv.style.padding = "10px";

    const image = document.createElement("img");
    image.src = img;
    image.style.width = "100px";
    myDiv.appendChild(image);

    const infoDiv = document.createElement("div");
    infoDiv.className = "product-Info";

    const p1 = document.createElement("p");
    p1.innerText = nameCar;
    infoDiv.appendChild(p1);

    const p2 = document.createElement("p");
    p2.innerText = "Giá: " + price;
    infoDiv.appendChild(p2);

    const link = document.createElement("a");
    // Gán ID vào href để trình duyệt hiển thị ở góc dưới bên trái
    link.href = "product-detail.html?id=" + id; 
    link.innerText = "Xem chi tiết";
    link.style.color = "blue";
    link.style.textDecoration = "underline";
    
    infoDiv.appendChild(link);
    myDiv.appendChild(infoDiv);
    container.appendChild(myDiv);
}
